def gen_objects():
    lines = []
    lines.append("# 业务对象层（Business Object Layer）")
    lines.append("")
    lines.append("> **定位**：三层架构的最底层。企业核心业务能力 = 业务对象行为方法的组合；企业的场景流程 = 业务能力的组装编排。")
    lines.append("> **本层交付**：列出全部业务对象（基于第3章数据架构14个数据域L4对象 + MDM主数据清单），每个含 **对象名称 / 对象说明 / 对象行为方法 / 所属业务域**。")
    lines.append("> **覆盖范围**：14个业务域（D01-D14），核心价值域（研发/供应链/制造/营销/销售/服务/生态）+ 支撑域（战略/人力/财务/法务/安全/IT/行政），共 %d 个业务对象。" % len(objects))
    lines.append("")
    # TOC by domain
    lines.append("## 业务对象总览（按业务域）")
    lines.append("")
    lines.append("| 业务域 | 对象数 |")
    lines.append("|---|---|")
    from collections import OrderedDict
    cnt = OrderedDict()
    for o in objects:
        cnt[o[2]] = cnt.get(o[2], 0) + 1
    for k, v in cnt.items():
        lines.append("| %s | %d |" % (k, v))
    lines.append("")
    lines.append("---")
    lines.append("")
    # detail
    for i, o in enumerate(objects, 1):
        cn, en, dom, cat, desc, methods = o
        lines.append("## %d. %s（`%s`）" % (i, cn, en))
        lines.append("")
        lines.append("- **所属业务域**：%s" % dom)
        lines.append("- **数据分类**：%s" % cat)
